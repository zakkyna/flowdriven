export type ErrorReason = keyof typeof REASON_CODE;
export type ErrorParams = Record<string, string | number | string[]>;
export class RunnerError extends Error {
  readonly code: RunnerErrorCode;
  readonly reason?: ErrorReason;
  readonly params?: ErrorParams;
  constructor(code: RunnerErrorCode, message: string, opts?: { reason?: ErrorReason; params?: ErrorParams }) {
    super(message);
    this.name = "RunnerError";
    this.code = code;
    this.reason = opts?.reason;
    this.params = opts?.params;
  }
}
export function isRunnerError(value: unknown): value is RunnerError {
  return value instanceof RunnerError;
}
